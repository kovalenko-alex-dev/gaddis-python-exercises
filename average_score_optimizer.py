def get_average_without_lowest(scores):
    """
    Вычисляет средний балл из списка, автоматически отбрасывая один самый худший результат.
    """
    # Защита от деления на ноль: если передан пустой список или всего 1 оценка,
    # то отбросить её и поделить на (1 - 1 = 0) не получится. Возвращаем 0.
    if len(scores) <= 1:
        return 0

    # Оптимизация: sum() находит общую сумму списка, min() находит худшую оценку.
    # Мы вычитаем минимальный балл из общей суммы, избегая громоздких циклов for.
    total = sum(scores) - min(scores)
    
    # Расчет среднего балла. 
    # ВАЖНО: скобки вокруг (len(scores) - 1) обязательны, чтобы деление шло 
    # на скорректированное количество элементов, а не вычиталось единица из результата.
    average = total / (len(scores) - 1)
    
    return average


# --- Блок демонстрации работы скрипта ---
if __name__ == '__main__':
    # Тестовый список оценок студента
    user_scores = [8, 9, 10, 7, 10]
    
    print("Исходные оценки:", user_scores)
    
    # Вызов функции
    final_result = get_average_without_lowest(user_scores)
    
    # Ожидаемый вывод: худшая оценка (7) отброшена, среднее по (8, 9, 10, 10) равно 9.25
    print(f"Средний балл (без учета худшего результата): {final_result}")
