# Создаем пустую таблицу размером 3 строки на 3 столбца, заполненную нулями
# "for _ in range(3)" — это конвейер, который 3 раза создает НОВУЮ независимую строку
matrix = [[0 * 3] for _ in range(3)]

# Меняем элемент в первой строке (индекс 0), в первом столбце (индекс 0)
matrix[0][0] = 5

# Печатаем результат
print(matrix)
# Выведет: [[5, 0, 0], [0, 0, 0], [0, 0, 0]]
# Изменилась ТОЛЬКО одна ячейка, все остальные строки остались независимыми
