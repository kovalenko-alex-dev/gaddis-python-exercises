def write_clean_file(filename, data_list):
    """
    Безопасно записывает элементы списка в файл, автоматически
    добавляя символ переноса строки (\\n) к каждому элементу.
    """
    # Менеджер контекста 'with' гарантирует автоматическое сохранение и закрытие файла.
    # Флаг 'w' — режим перезаписи (создает файл с нуля или затирает старый).
    with open(filename, 'w', encoding='utf-8') as f:
        # Продвинутый паттерн: передаем генератор в .writelines().
        # Мы не модифицируем исходный список в памяти, а динамически
        # подставляем '\\n' к каждому элементу прямо в процессе записи.
        f.writelines(f"{item}\n" for item in data_list)


# --- Блок демонстрации работы скрипта ---
if __name__ == '__main__':
    # Наш исходный чистый список без всяких \n
    products = ['молоко', 'хлеб', 'яблоки', 'кофе']
    output_filename = 'exported_products.txt'
    
    print(f"Записываем список из {len(products)} элементов в файл '{output_filename}'...")
    
    # Вызов функции записи
    write_clean_file(output_filename, products)
    
    print("Запись успешно завершена! Проверяем содержимое файла:")
    
    # Проверяем, что записалось (читаем файл "как есть")
    with open(output_filename, 'r', encoding='utf-8') as verify_f:
        print(verify_f.read())

