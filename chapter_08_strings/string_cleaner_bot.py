# Паттерн: Обработка строковых данных для парсеров и Telegram-ботов

# 1. Очистка текста от "мусора" (Парсинг)
# Часто с сайтов собирается текст с кучей пробелов, переносов строк и лишних символов
raw_price = "   \n 12500 руб. \t "
# strip() удаляет невидимые символы по краям, replace() убирает валюту
clean_price = raw_price.strip().replace("руб.", "").strip()
print(f"Очищенная цена для базы данных: '{clean_price}'")  # Выведет: '12500'


# 2. Проверка команд (Телеграм-боты)
# Пользователь может написать /start, /Start или /START. Приводим к нижнему регистру.
user_message = "/Start"
if user_message.lower().startswith("/start"):
    print("Бот: Приветствую! Вы запустили команду /start")


# 3. Валидация ввода пользователя (Боты)
# Проверяем, ввёл ли пользователь число (например, ID товара или сумму)
user_input = "4589"
if user_input.isdigit():
    product_id = int(user_input)
    print(f"Корректный ID товара: {product_id}")
else:
    print("Ошибка: Пожалуйста, введите только цифры!")
