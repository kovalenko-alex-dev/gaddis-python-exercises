# Демонстрация генераторов списков (List Comprehensions) и f-строк для парсеров и ботов

# 1. Массовая очистка данных с парсера в одну строку
print('--- 1. Парсинг: очистка списка цен ---')
raw_prices = [' 1 200 руб.', '450 руб.', ' Нет в наличии ', ' 8 990 руб.']

# Берём только те строки, где есть 'руб.', удаляем лишнее и сразу переводим в int
clean_prices = [
    int(item.replace(' ', '').replace('руб.', ''))
    for item in raw_prices
    if 'руб.' in item
]
print('Чистые числа из парсера:', clean_prices)

# 2. Фильтрация ссылок при сборе страниц (скрапинге)
print('\n--- 2. Парсинг: фильтрация нужных ссылок ---')
scraped_links = [
    'https://site.com',
    'https://site.com',
    'https://site.com',
    'https://t.me'
]

# Оставляем только ссылки на товары из каталога
product_links = [link for link in scraped_links if '/catalog/' in link]
print('Ссылки на товары:', product_links)

# 3. Фишки для ботов: фильтрация ID и сборка красивого ответа через f-строки
print('\n--- 3. Бот: рассылка и форматирование отчёта ---')
# База пользователей из текстового файла или таблицы (есть битые записи и дубли)
raw_user_ids = ['104523', 'admin', '998123', '', '445120', 'banned_user']

# Оставляем только валидные числовые ID для рассылки
valid_ids = [int(uid) for uid in raw_user_ids if uid.isdigit()]
print(f'Готово к рассылке: {len(valid_ids)} пользователей -> {valid_ids}')

# Сборка красивого сообщения для Telegram-бота из спарсенных данных
items = [('Клавиатура', 3500), ('Мышь', 1800), ('Коврик', 650)]

# Генерируем строки прайс-листа с выравниванием и разделителем тысяч (:,)
report_lines = [f'• {name:<12} | {price:,} ₽'.replace(',', ' ') for name, price in items]

bot_message = (
    '📊 **Актуальный прайс-лист:**\n'
    + '\n'.join(report_lines)
    + f'\n\n💰 **Итого:** {sum(clean_prices):,} ₽'.replace(',', ' ')
)
print('\n--- Итоговое сообщение бота ---')
print(bot_message)
