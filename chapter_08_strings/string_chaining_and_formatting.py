# Демонстрация цепочек вызовов (chaining), подсчёта слов и динамического форматирования

# 1. Цепочка вызовов: split() сразу превращается в список, к которому применяется индекс
print('--- 1. Цепочки вызовов (Chaining) ---')
date_str = '2026-11-23'
month = date_str.split('-')[1]  # Без создания лишней промежуточной переменной
print(f'Извлечённый месяц: {month}')

# Разница между пустым split() и явным разделителем split(',')
csv_row = 'Иван,,Херсон'
print('Разбор CSV с пустым полем:', csv_row.split(','))  # ['Иван', '', 'Херсон']

# 2. Разница len() для строки и для списка слов
print('\n--- 2. Подсчёт символов и слов ---')
raw_phrase = '  one   two   three  '
print('Длина строки (символы):', len(raw_phrase.strip()))  # 17 (считает буквы и пробелы)
print('Количество слов (список):', len(raw_phrase.split()))  # 3 (split() сам убирает лишние пробелы)

# 3. Динамическая рамка (избегаем хардкода ширины)
print('\n--- 3. Динамическое оформление (оператор *) ---')
title = 'Bot Admin Panel'
border = '=' * (len(title) + 4)  # +4 учитывает две стенки '|' и два пробела вокруг текста

print(border)
print(f'| {title} |')
print(border)

# 4. Циклы range(): прямая и обратная лесенка (правая граница stop не включается)
print('\n--- 4. Прямой и обратный отсчёт в range() ---')
for i in range(1, 4):
    print('*' * i)

print('---')

for i in range(3, 0, -1):  # Останавливается на 1, не доходя до 0
    print('*' * i)
