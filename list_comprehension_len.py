# Исходный список слов для обработки
str_list = ['Мигнуть', 'Моргнуть', 'Кивнуть']

# ==============================================================================
# ПАТТЕРН: Трансформация списка с фильтрацией (List Comprehension + IF)
# ==============================================================================
# Формула: [выражение_результата выражение_итерации выражение_условия]
# 
# len(s)             -> Выражение результата (что положить в итог)
# for s in str_list   -> Выражение итерации (цикл-транспорт)
# if len(s) > 7      -> Выражение условия (фейсконтроль / фильтр)
#
filtered_lengths = [len(s) for s in str_list if len(s) > 7]

# --- Блок демонстрации работы скрипта ---
if __name__ == '__main__':
    print("Исходный список:", str_list)
    
    # Ожидаемый вывод: [8] (так как только в слове 'Моргнуть' больше 7 букв)
    print("Результат фильтрации и замера длин:", filtered_lengths)
    
    print("\nРазбор логики:")
    print("1. Слово 'Мигнуть' (7 букв) -> не прошло условие > 7")
    print("2. Слово 'Моргнуть' (8 букв) -> прошло, его длина (8) добавлена в список")
    print("3. Слово 'Кивнуть' (7 букв) -> не прошло условие > 7")
